// Public Suffix List → src/data/public-suffix-list.mjs (cookie-parser)
//
// Read:  the Public Suffix List at the pinned commit. Default: download
//        https://raw.githubusercontent.com/publicsuffix/list/<COMMIT>/public_suffix_list.dat.
//        --file <path>: use a local copy instead (the git file, or the file served by
//        https://publicsuffix.org/list/public_suffix_list.dat while it was this version; the
//        served file only adds the "// VERSION:" and "// COMMIT:" header lines).
// Write: src/data/public-suffix-list.mjs (generated, committed). --check writes nothing and
//        exits 1 when the committed module differs from what this source produces.
// Exit:  0 on success; 1 when the SHA-256 is not one of the pinned values, the header names
//        another version, a rule cannot be converted, or --check finds a difference.
//
// The module keeps every rule of both sections (ICANN and PRIVATE), including wildcard (*.)
// and exception (!) rules. Unicode rules are converted to ASCII (punycode, Node url.domainToASCII)
// because the cookie engine only sees ASCII hosts and Domain attributes; when the list has both
// forms of a rule, the first one is kept. The list is MPL-2.0; the module carries the notice.
//
// Updating to a newer list (see scripts/AGENTS.md):
//   1. pick a commit of github.com/publicsuffix/list; set COMMIT, VERSION (the "// VERSION:" line
//      publicsuffix.org serves for it) and the two SHA-256 values below;
//   2. node scripts/sync-public-suffix-list.mjs, then node scripts/test-cookie-parser.mjs
//      (test_psl.txt of the same commit goes to scripts/test-cookie-parser.test_psl.txt).
//
// Run: node scripts/sync-public-suffix-list.mjs [--file <path>] [--check]

import { readFileSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { domainToASCII } from 'node:url';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

export const COMMIT = '6cd82aff889e3d64e5e03bc5c1f43da1934a960a';
export const VERSION = '2026-10-01_23-02-52_UTC';
// SHA-256 of public_suffix_list.dat in git at COMMIT
export const SHA256_GIT = '102b252c18b5f87f4c81f017e75282a82c18e00cd0c2e601b5b02a0f7a601f2c';
// SHA-256 of the same list as publicsuffix.org served it (git file + VERSION / COMMIT lines)
export const SHA256_SERVED = 'e0fe072d26b0536525badea237953ff451c9f8e64c9d02c6daa81a4491d2fc66';
export const SOURCE_URL = `https://raw.githubusercontent.com/publicsuffix/list/${COMMIT}/public_suffix_list.dat`;

const root = dirname(dirname(fileURLToPath(import.meta.url)));
const OUT = join(root, 'src/data/public-suffix-list.mjs');

export function sha256(text) { return createHash('sha256').update(text, 'utf8').digest('hex'); }

function toAsciiRule(rule) {
  let prefix = '';
  let body = rule;
  if (body[0] === '!') { prefix = '!'; body = body.slice(1); }
  if (body.startsWith('*.')) { prefix += '*.'; body = body.slice(2); }
  if (body.includes('*') || body.includes('!')) throw new Error(`unsupported rule shape: ${rule}`);
  const ascii = /^[\x21-\x7e]+$/.test(body) ? body.toLowerCase() : domainToASCII(body);
  if (!ascii) throw new Error(`cannot convert rule to ASCII: ${rule}`);
  return prefix + ascii;
}

// Parse per publicsuffix.org/list: one rule per line, the rule ends at the first whitespace,
// "//" lines are comments; sections are delimited by the BEGIN / END markers.
export function parseList(text) {
  const out = { icann: [], private: [], unicode: 0, duplicates: 0 };
  const seen = new Set();
  let section = null;
  for (const raw of text.split(/\r?\n/)) {
    const line = raw.trim();
    if (line === '// ===BEGIN ICANN DOMAINS===') { section = 'icann'; continue; }
    if (line === '// ===BEGIN PRIVATE DOMAINS===') { section = 'private'; continue; }
    if (/^\/\/ ===END (ICANN|PRIVATE) DOMAINS===$/.test(line)) { section = null; continue; }
    if (!line || line.startsWith('//')) continue;
    if (!section) throw new Error(`rule outside a section: ${line}`);
    const rule = line.split(/\s/)[0];
    const ascii = toAsciiRule(rule);
    if (ascii !== rule) out.unicode++;
    if (seen.has(ascii)) { out.duplicates++; continue; }
    seen.add(ascii);
    out[section].push(ascii);
  }
  return out;
}

export function verifySource(text) {
  const sum = sha256(text);
  if (sum === SHA256_GIT) return 'git';
  if (sum === SHA256_SERVED) {
    if (!text.includes(`// VERSION: ${VERSION}\n`) || !text.includes(`// COMMIT: ${COMMIT}\n`)) throw new Error('served file header does not name the pinned version');
    return 'served';
  }
  throw new Error(`SHA-256 ${sum} is neither the pinned git file (${SHA256_GIT}) nor the served file (${SHA256_SERVED})`);
}

export function buildModule(text) {
  verifySource(text);
  const p = parseList(text);
  const head = [
    '// GENERATED by scripts/sync-public-suffix-list.mjs. Do not edit; rerun the script.',
    '//',
    '// Public Suffix List (https://publicsuffix.org/), all rules of the ICANN and PRIVATE sections,',
    '// including wildcard (*.) and exception (!) rules, Unicode rules converted to ASCII (punycode).',
    `// Source: ${SOURCE_URL}`,
    `// Version: ${VERSION}; commit ${COMMIT}`,
    `// SHA-256 of the source: ${SHA256_GIT} (git) / ${SHA256_SERVED} (as served by publicsuffix.org)`,
    '//',
    '// This Source Code Form is subject to the terms of the Mozilla Public License, v. 2.0.',
    '// If a copy of the MPL was not distributed with this file, You can obtain one at',
    '// https://mozilla.org/MPL/2.0/.',
    '',
  ].join('\n');
  const data = {
    version: VERSION,
    commit: COMMIT,
    sha256: SHA256_GIT,
    license: 'MPL-2.0',
    icann: p.icann.join('\n'),
    private: p.private.join('\n'),
  };
  const body = 'export default {\n' + Object.entries(data).map(([k, v]) => `  ${k}: ${JSON.stringify(v)},`).join('\n') + '\n};\n';
  return { text: head + body, stats: { icann: p.icann.length, private: p.private.length, unicode: p.unicode, duplicates: p.duplicates } };
}

async function main() {
  const args = process.argv.slice(2);
  const fi = args.indexOf('--file');
  let text;
  if (fi >= 0) text = readFileSync(args[fi + 1], 'utf8');
  else {
    const res = await fetch(SOURCE_URL);
    if (!res.ok) throw new Error(`download failed: HTTP ${res.status} ${SOURCE_URL}`);
    text = await res.text();
  }
  const kind = verifySource(text);
  const { text: mod, stats } = buildModule(text);
  if (args.includes('--check')) {
    const cur = readFileSync(OUT, 'utf8');
    if (cur !== mod) { console.error('FAIL: src/data/public-suffix-list.mjs differs from the pinned list'); process.exit(1); }
    console.log(`OK: module matches the pinned list (${kind} file)`);
    return;
  }
  writeFileSync(OUT, mod);
  console.log(`wrote src/data/public-suffix-list.mjs from the ${kind} file: ${stats.icann} ICANN + ${stats.private} PRIVATE rules (${stats.unicode} converted to ASCII, ${stats.duplicates} duplicates dropped), ${Buffer.byteLength(mod)} bytes`);
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  main().catch((e) => { console.error('FAIL: ' + e.message); process.exit(1); });
}
